// Lifts the preloader's moustache outline out of the templates into a module
// the chrome can import, so the path is never retyped by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => fs.readFileSync(path.join(HERE, 'src', 'pages', p, 'template.resolved.html'), 'utf8');

const m = read('about').match(/<path data-mark-path="" style="\{\{ preloaderMarkPathStyle \}\}" d="([^"]+)"/);
if (!m) throw new Error('mark path not found');
for (const p of ['home', 'work', 'services', 'contact']) {
  if (!read(p).includes(m[1])) throw new Error(`mark path differs on ${p}`);
}

const outDir = path.join(HERE, '..', 'next', 'app', '_chrome');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'mark-path.js'),
  '// The moustache outline from the preloader, lifted verbatim from the bundled\n' +
    '// templates (identical in all five). Generated by .migration/build-mark-path.mjs.\n' +
    'export const MARK_PATH =\n  ' +
    JSON.stringify(m[1]) +
    ';\n',
);

console.log(`mark path: ${m[1].length} chars, identical on all five pages`);
